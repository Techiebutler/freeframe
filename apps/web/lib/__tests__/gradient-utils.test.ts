// @vitest-environment node
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import { describe, expect, it } from 'vitest'
import config from '../../tailwind.config'
import { GRADIENT_PRESETS, getGradientForProject } from '../gradient-utils'

describe('project card gradients', () => {
  it('are generated by Tailwind, not purged', async () => {
    // Tailwind only emits classes it finds in `content`; a preset it never
    // sees renders as no background at all, which is a plain grey card.
    const { css } = await postcss([tailwindcss(config)]).process('@tailwind utilities;', {
      from: undefined,
    })
    const classes = GRADIENT_PRESETS.flatMap((preset) => preset.split(' '))
    const missing = classes.filter((cls) => !css.includes(`.${cls} {`))
    expect(missing).toEqual([])
  })

  it('picks the same preset for the same project', () => {
    const id = '7c9e6679-7425-40de-944b-e07fc1f90ae7'
    expect(getGradientForProject(id)).toBe(getGradientForProject(id))
    expect(GRADIENT_PRESETS).toContain(getGradientForProject(id))
  })
})
